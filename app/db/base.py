"""SQLAlchemy declarative base with a deterministic naming convention.

Deterministic constraint/index names keep Alembic autogenerate diffs stable.
No models are defined in Phase 1; the schema is introduced (via Alembic) in a
later phase. This module exists so models and migrations share one MetaData.
"""

from __future__ import annotations

from sqlalchemy import MetaData
from sqlalchemy.orm import DeclarativeBase

NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)
